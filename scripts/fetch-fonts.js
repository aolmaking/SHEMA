/* Downloads the Arabic + Latin subsets of the webfonts the widgets use and
   writes a local @font-face sheet, so everything renders offline. */
const fs = require('fs');
const path = require('path');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0.0.0 Safari/537.36';
const OUT = path.join(__dirname, '..', 'assets', 'fonts');

const FAMILIES = [
  // reading: Quran, hadith, tafsir
  { q: 'Amiri+Quran', slug: 'amiri-quran' },
  { q: 'Amiri:wght@400;700', slug: 'amiri' },
  { q: 'Scheherazade+New:wght@400;700', slug: 'scheherazade' },
  { q: 'Noto+Naskh+Arabic:wght@400;500;600;700', slug: 'noto-naskh' },
  // interface
  { q: 'IBM+Plex+Sans+Arabic:wght@200;300;400;500;600;700', slug: 'plex-arabic' },
  { q: 'Cairo:wght@200..1000', slug: 'cairo' },
  { q: 'Tajawal:wght@300;400;500;700', slug: 'tajawal' },
  { q: 'Almarai:wght@300;400;700', slug: 'almarai' },
  { q: 'Readex+Pro:wght@160..700', slug: 'readex' },
  { q: 'Noto+Kufi+Arabic:wght@100..900', slug: 'noto-kufi' },
  { q: 'El+Messiri:wght@400..700', slug: 'el-messiri' },
  // numerals
  { q: 'Outfit:wght@100..900', slug: 'outfit' },
];

// Keep the subsets that actually carry Arabic glyphs or basic Latin/digits.
function wanted(range) {
  if (!range) return false;
  const arabic = /U\+06|U\+07|U\+08|U\+FB5|U\+FE7|U\+FDF/i.test(range);
  const latin = /U\+0000-00FF|U\+0-00FF/i.test(range);
  return arabic || latin;
}

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  let sheet = '/* Generated by scripts/fetch-fonts.js — local copies, OFL licensed. */\n';
  for (const fam of FAMILIES) {
    const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${fam.q}&display=swap`, { headers: { 'User-Agent': UA } })).text();
    const blocks = css.split('@font-face').slice(1);
    let i = 0;
    for (const b of blocks) {
      const url = (b.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
      const range = (b.match(/unicode-range:\s*([^;]+);/) || [])[1];
      const weight = (b.match(/font-weight:\s*([^;]+);/) || [])[1] || '400';
      const family = (b.match(/font-family:\s*'([^']+)'/) || [])[1];
      if (!url || !wanted(range)) continue;
      const file = `${fam.slug}-${weight.trim().replace(/\s+/g, '-')}-${i++}.woff2`;
      const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
      fs.writeFileSync(path.join(OUT, file), buf);
      sheet += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight.trim()};font-display:swap;src:url('fonts/${file}') format('woff2');unicode-range:${range.trim()};}\n`;
      console.log(`saved ${file} (${(buf.length / 1024).toFixed(1)} KB)`);
    }
  }
  fs.writeFileSync(path.join(OUT, '..', 'fonts.css'), sheet);
  console.log('wrote assets/fonts.css');
}
main().catch((e) => { console.error(e); process.exit(1); });
