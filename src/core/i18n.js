function translator(getLang) {
  return (key, vars) => {
    const lang = getLang() === 'en' ? 'en' : 'ar';
    let str = STRINGS[lang][key] ?? STRINGS.ar[key] ?? key;
    if (vars) str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    return str;
  };
}

